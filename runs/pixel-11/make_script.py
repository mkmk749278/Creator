out.write_text(json.dumps(script, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
words = sum(len((l.get("say") or l["text"]).split()) for p in script["parts"] for l in p["lines"])
print(f"wrote {out}: {len(script['parts'])} parts, {words} spoken words (~{words/155:.1f} min)")
