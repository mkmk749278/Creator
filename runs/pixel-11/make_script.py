for pid, title, lines in PARTS:
    script["parts"].append({"id": pid, "title": title, "lines": [
        {"id": f"{pid}-{i+1:02d}", "speaker": s, "text": t, **({"say": say} if say else {}), "beat": beat}
        for i, (s, t, say, beat) in enumerate(lines)
    ]})

