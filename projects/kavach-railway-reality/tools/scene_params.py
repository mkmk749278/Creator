#!/usr/bin/env python3
"""Write video/kavach-railway-reality/<scene>/cues.js (window.CUES: duration, per-line cues, breaks) from scenes.json.

Compositions read CUES so every beat is keyed to the real VO timing; re-run after a re-alignment and re-render.
`word(lineId, fraction)` in _shared/kav.js places a word inside a line by its share of the line's characters.

  python3 projects/kavach-railway-reality/tools/scene_params.py [scene_id ...]
"""
import json, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent
VID = HERE.parent.parent / "video" / "kavach-railway-reality"
S = json.load(open(HERE / "scenes.json"))
for sid in (sys.argv[1:] or S):
    s = S[sid]; d = VID / sid; d.mkdir(parents=True, exist_ok=True)
    out = dict(id=sid, duration=s["duration"], cues={c["id"]: dict(at=c["at"], to=c["to"], vo=c["vo"]) for c in s["cues"]},
               breaks=s["breaks"])
    (d / "cues.js").write_text("// generated by projects/kavach-railway-reality/tools/scene_params.py: do not edit\nwindow.CUES = "
                               + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    print(sid, s["duration"])
