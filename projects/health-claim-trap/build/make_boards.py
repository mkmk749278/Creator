#!/usr/bin/env python3
"""Write one whiteboard scene per entry in boards.py: video/healthclaim/<id>/{index.html, params.js}."""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from boards import BOARDS

ROOT = Path(__file__).resolve().parents[3]
LIB, OUT = ROOT / "video/lib/whiteboard", ROOT / "video/healthclaim"


def put(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


for i, b in enumerate(BOARDS):
    d = OUT / b["id"]; d.mkdir(parents=True, exist_ok=True)
    dur = round(b["end"] - b["start"], 2)
    put(d / "index.html", re.sub(r'data-duration="[\d.]+"', f'data-duration="{dur}"', (LIB / "index.html").read_text()))
    steps = [dict(s, at=round(s["at"] - b["start"], 2)) if "at" in s else s for s in b["steps"]]
    scene = dict(duration=dur, seed=40 + i, font="tech", tag=b["tag"],
                 camera=[dict(at=0, scale=1.0, x=0, y=0), dict(at=dur, scale=1.04, x=-16 if i % 2 else 16, y=0)], steps=steps)
    put(d / "params.js", f"// Generated by projects/health-claim-trap/build/make_boards.py ({b['start']:.2f}–{b['end']:.2f} s of the film)\n"
                         "window.SCENE = " + json.dumps(scene, ensure_ascii=False, indent=1) + ";\n")
    print(b["id"], f"{b['start']:.2f}", dur)
