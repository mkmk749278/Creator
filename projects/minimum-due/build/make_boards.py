#!/usr/bin/env python3
"""Write one whiteboard scene per segment in boards.py: video/minimumdue/<id>/{index.html, params.js}."""
import json, re, shutil, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from boards import BOARDS

ROOT = Path(__file__).resolve().parents[3]
LIB = ROOT / "video/lib/whiteboard"
OUT = ROOT / "video/minimumdue"

def put(path, text):
    """Write only on change, so render_boards.sh re-renders only the boards that changed."""
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def rel(step, t0):
    s = dict(step)
    if "at" in s: s["at"] = round(s["at"] - t0, 2)
    return s

for i, b in enumerate(BOARDS):
    d = OUT / b["id"]; d.mkdir(parents=True, exist_ok=True)
    dur = round(b["end"] - b["start"], 2)
    html = (LIB / "index.html").read_text()
    html = re.sub(r'data-duration="[\d.]+"', f'data-duration="{dur}"', html)
    put(d / "index.html", html)
    scene = dict(duration=dur, seed=20 + i, font="tech", tag=b.get("tag", ""),
                 camera=[dict(at=0, scale=1.0, x=0, y=0), dict(at=dur, scale=1.04, x=-16 if i % 2 else 16, y=0)],
                 steps=[rel(s, b["start"]) for s in b["steps"]])
    put(d / "params.js", f"// Generated by projects/minimum-due/build/make_boards.py ({b['start']:.2f}–{b['end']:.2f} s of the film)\n"
                                 "window.SCENE = " + json.dumps(scene, ensure_ascii=False, indent=1) + ";\n")
    print(b["id"], dur)
