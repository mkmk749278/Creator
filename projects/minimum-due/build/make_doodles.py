#!/usr/bin/env python3
"""Write one doodle scene per entry in doodles.py: video/minimumdue/<id>/{index.html, params.js, paper.jpg, sfx.json}.
Replaces the whiteboard pages of the same ids (the whiteboard versions stay in git history). Times become relative to the
board's start; sound cues follow the items (draw → scribble, pop → pop, stamp → thud, move → whoosh, coins → clink)."""
import json, re, shutil, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from boards import BOARDS
from doodles import DOODLES

ROOT = Path(__file__).resolve().parents[3]
LIB, OUT = ROOT / "video/lib/doodle", ROOT / "video/minimumdue"
B = {b["id"]: b for b in BOARDS}
DRAWN = {"bill", "coins", "card", "pos", "phone", "calendar", "meter", "toggle", "net", "scale", "bars", "arrow", "loop", "box",
         "contact", "house", "slider", "seesaw", "calc", "ring", "strike", "cross"}


def put(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def rel(it, t0, dur):
    r = lambda t: round(min(dur, max(0.0, t - t0)), 2)
    o = {("in" if k == "in_" else k): v for k, v in it.items()}
    for k in ("at", "hlAt", "onAt", "bandAt", "bandShatterAt", "exit"):
        if k in o:
            o[k] = r(o[k])
    if "moves" in o:
        o["moves"] = [dict(m, at=r(m["at"])) for m in o["moves"]]
    for k in ("needle", "tilt", "spin", "knob"):
        if k in o:
            o[k] = [[0, v[1]] if i == 0 else [r(v[0]), *v[1:]] for i, v in enumerate(o[k])]
    if "grow" in o:
        o["grow"] = [r(t) for t in o["grow"]]
    return o


def sfx(items):
    cues = []
    for it in items:
        how = it.get("in") or ("draw" if it["kind"] in DRAWN else "pop")
        snd = {"draw": "scribble", "pop": "pop", "stamp": "thud", "slide": "whoosh"}[how]
        if it["kind"] == "coins":
            snd = "clink"
        if it["kind"] == "cross":
            snd = "thud"
        cues.append([it["at"], snd])
        cues += [[m["at"], "whoosh"] for m in it.get("moves", [])]
        if it.get("onAt") is not None:
            cues.append([it["onAt"], "pop"])
        cues += [[t, "pop"] for t in it.get("grow", [])]
    exits = sorted({it["exit"] for it in items if it.get("exit") is not None})
    cues += [[t, "whoosh"] for t in exits]
    cues.sort()
    out = []
    for c in cues:   # one sound per kind within 0.25 s, at most one cue per 0.12 s
        if out and (c[0] - out[-1][0] < 0.12 or (c[1] == out[-1][1] and c[0] - out[-1][0] < 0.25)):
            continue
        out.append(c)
    return out


def cam(items, dur, push=0.07):
    """Camera keys: each page (items sharing a page-turn time) gets a slow push toward its content's centre, from the
    page's first item to its turn; the camera resets during the page turn. No page ever sits still."""
    turns = sorted({it["exit"] for it in items if it.get("exit") is not None and it["exit"] < dur - 0.3}) + [dur]
    keys, t_prev = [[0, 1.0, 0, 0, 0]], 0.0
    for turn in turns:
        its = [it for it in items if (it.get("exit") if it.get("exit") is not None and it["exit"] < dur - 0.3 else dur) == turn]
        if not its:
            continue
        t0 = max(t_prev, min(it["at"] for it in its) - 0.2)
        xs = [it.get("x", 960) + (0 if it.get("anchor") == "middle" or it["kind"] in ("scale", "meter", "loop", "coins") else 150) for it in its]
        ys = [it.get("y", 540) + (0 if it["kind"] in ("label", "scale", "meter", "loop") else 100) for it in its]
        cx, cy = sum(xs) / len(xs), sum(ys) / len(ys)
        keys.append([round(t0, 2), 1.0, 0, 0, 0.01])
        keys.append([round(t0 + 0.02, 2), round(1 + push, 3), round(-(cx - 960) * push, 1), round(-(cy - 540) * push, 1), round(max(0.6, turn - t0 - 0.05), 2)])
        t_prev = turn + 0.36   # page-turn exit lasts 0.35 s
    return keys


for bid, d in DOODLES.items():
    b = B[bid]; t0 = b["start"]; dur = round(b["end"] - t0, 2)
    items = [rel(it, t0, dur) for it in d["items"]]
    for it in items:   # optional whole-scene vertical shift (doodles.py: shift=…)
        it["y"] = it.get("y", 0) + d.get("shift", 0)
        for m in it.get("moves", []):
            if "y" in m:
                m["y"] += d.get("shift", 0)
    scene = dict(duration=dur, tag=d.get("tag", ""), kicker=d.get("kicker", ""), items=items, sfx=sfx(items), cam=cam(items, dur))
    f = OUT / bid; f.mkdir(parents=True, exist_ok=True)
    for old in ("vendor/wb",):
        shutil.rmtree(f / old, ignore_errors=True)
    html = (LIB / "scene.html").read_text()
    html = re.sub(r'data-duration="[\d.]+"', f'data-duration="{dur}"', html)
    put(f / "index.html", html)
    put(f / "params.js", f"// Generated by projects/minimum-due/build/make_doodles.py from build/doodles.py ({t0:.2f}–{b['end']:.2f} s of the film)\n"
                         "window.SCENE = " + json.dumps(scene, ensure_ascii=False, indent=1) + ";\n")
    (f / "paper.jpg").unlink(missing_ok=True)   # the paper texture comes from vendor/doodle/ now
    print(bid, dur, len(items), "items", len(scene["sfx"]), "sounds")
