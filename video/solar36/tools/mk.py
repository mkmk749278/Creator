#!/usr/bin/env python3
"""Generate film 36 scene compositions from video/solar36/scenes.json (edit the scene JS + this list, then re-run).

Each scene folder gets: index.html (shared CSS, HUD, tags, logo bug, grain/vignette, optional video shots),
copies of _shared/world.js + kit.js, its own Sxx.js, vendor/ (GSAP + Inter), and media/ for its clips.
Timing comes from the final edit's exact line times (projects/solar-anti-islanding/align_take2/edit3_lines_exact.json);
scene JS gets ctx.V(t) to turn a VO time into local scene time.

  python3 video/solar36/tools/mk.py            # all scenes
  python3 video/solar36/tools/mk.py S01 S02    # some
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FILM = ROOT / "video/solar36"
PROJ = ROOT / "projects/solar-anti-islanding"
LINES = json.loads((PROJ / "align_take2/edit3_lines_exact.json").read_text())
CSS = (FILM / "_shared/film.css").read_text()

EXTRA_CSS = """
  .lab { position: absolute; padding: 10px 22px; background: rgba(13,17,23,0.84); color: #E6EDF3; border-radius: 10px;
    font: 800 40px Inter, Arial, sans-serif; letter-spacing: 0.08em; border-left: 6px solid #58a6ff; opacity: 0; white-space: nowrap; }
  .lab.red { border-left-color: #f85149; } .lab.green { border-left-color: #3fb950; } .lab.amber { border-left-color: #d29922; }
  #whatif { position: absolute; inset: 18px; border: 6px dashed rgba(248,81,73,0.85); border-radius: 18px; opacity: 0; pointer-events: none; }
  #whatif span { position: absolute; left: 50%; top: 22px; transform: translateX(-50%); padding: 8px 20px; background: #f85149; color: #fff;
    font: 800 34px Inter, Arial, sans-serif; letter-spacing: 0.14em; border-radius: 8px; }
  .shot { position: absolute; inset: 0; overflow: hidden; }
  .shot video { width: 100%; height: 100%; object-fit: cover; }
"""


def build(sc):
    sid, t0, t1 = sc["id"], sc["start"], sc["end"]
    dur = round(t1 - t0, 3)
    d = FILM / sid
    (d / "vendor/fonts").mkdir(parents=True, exist_ok=True)
    shutil.copy(ROOT / "node_modules/gsap/dist/gsap.min.js", d / "vendor/gsap.min.js")
    for w in (400, 600, 800):
        shutil.copy(ROOT / f"node_modules/@fontsource/inter/files/inter-latin-{w}-normal.woff2", d / "vendor/fonts")
    shutil.copy(ROOT / "node_modules/@fontsource/inter/files/inter-latin-ext-600-normal.woff2", d / "vendor/fonts")
    for f in ("world.js", "kit.js"):
        shutil.copy(FILM / "_shared" / f, d / f)
    shots = []
    for i, m in enumerate(sc.get("media", [])):
        (d / "media").mkdir(exist_ok=True)
        shutil.copy(PROJ / m["src"], d / "media" / Path(m["src"]).name)
        s, du = round(m["start"], 3), round(m["dur"], 3)
        shots.append(f'<div id="shot{i}" class="shot" style="visibility:hidden"><video id="v{i}" src="media/{Path(m["src"]).name}" muted playsinline '
                     f'data-start="{s}" data-duration="{du}" data-media-start="{m.get("mediaStart", 0)}" data-track-index="{2 + i}" data-volume="0"></video></div>')
    lines = [l for l in LINES if l["end"] > t0 and l["start"] < t1]
    html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=1920, height=1080" />
<title>Film 36 {sid}: {sc['title']}</title>
<!-- generated by video/solar36/tools/mk.py: edit {sid}.js / scenes.json / _shared, then re-run -->
<style>{CSS}{EXTRA_CSS}</style>
</head>
<body>
<div id="root" data-composition-id="solar36_{sid}" data-start="0" data-width="1920" data-height="1080" data-duration="{dur}">
  <svg id="stage" viewBox="0 0 1920 1080" data-layout-allow-overflow></svg>
  {''.join(shots)}
  <svg id="grain" viewBox="0 0 1920 1080" data-layout-allow-occlusion>
    <filter id="n"><feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2" seed="36" /><feColorMatrix type="saturate" values="0" /></filter>
    <rect width="1920" height="1080" filter="url(#n)" />
  </svg>
  <div id="vig" data-layout-allow-occlusion></div>
  <div id="whatif" data-layout-allow-occlusion><span>WHAT IF</span></div>
  <div id="hud"></div>
  <div id="bug">BE<br/>PRACTICAL</div>
  <div id="tag">ILLUSTRATION · SLOWED DOWN</div>
</div>
<script src="vendor/gsap.min.js"></script>
<script src="world.js"></script>
<script src="kit.js"></script>
<script src="{sid}.js"></script>
<script>
  const ctx = {{ D: {dur}, T0: {t0}, V: t => +(t - {t0}).toFixed(3), LINES: {json.dumps(lines)} }};
  const tl = gsap.timeline({{ paused: true }});
  const shots = {json.dumps([{"s": round(m["start"], 3), "d": round(m["dur"], 3)} for m in sc.get("media", [])])};
  shots.forEach((m, i) => {{ tl.set("#shot" + i, {{ visibility: "hidden" }}, 0).set("#shot" + i, {{ visibility: "visible" }}, m.s).set("#shot" + i, {{ visibility: "hidden" }}, Math.min(ctx.D, m.s + m.d)); }});
  window.SCENE(tl, ctx);
  window.__timelines = window.__timelines || {{}};
  window.__timelines["solar36_{sid}"] = tl;
</script>
</body>
</html>
"""
    (d / "index.html").write_text(html)
    src = FILM / "scenes" / f"{sid}.js"
    shutil.copy(src, d / f"{sid}.js")
    print(f"{sid}: {dur} s, {len(lines)} lines, {len(shots)} shots")


if __name__ == "__main__":
    scenes = json.loads((FILM / "scenes.json").read_text())
    want = set(sys.argv[1:])
    for sc in scenes:
        if not want or sc["id"] in want:
            build(sc)
