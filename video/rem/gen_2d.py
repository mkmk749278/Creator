    a = rnd.uniform(0, math.tau); r = 210 * math.sqrt(rnd.random())
    x, y = 960 + r * math.cos(a), 560 + 0.62 * r * math.sin(a); rot = rnd.uniform(0, 360)
    powder.append(f'<g class="pw" transform="translate({x:.0f},{y:.0f})"><g class="pr" data-r0="{rot:.0f}" transform="rotate({rot:.0f})">'
                  f'<rect x="-7" y="-2.5" width="14" height="5" rx="2" fill="#c9ced6"/><rect x="3" y="-2.5" width="4" height="5" fill="#58a6ff"/></g></g>')
