#!/usr/bin/env python3
"""Write the rare earth film's 3D scene compositions (video/rem/<scene>/index.html) from one Three.js template.

Each scene is a pure function of time t (seeded RNG, no state carried between frames): renderAt(t) builds the frame,
HyperFrames seeks it through the `hf-seek` event. HDRI lighting, ACES-like AgX tone mapping, bloom and vignette follow
the realism recipe (PLAYBOOK §9); no N8AO (it doubles render cost), contact shadows are faked with dark discs.
Labels and numbers are drawn later by the film engine (projects/rare-earth-magnets/build/make_film.py), not here.

  python3 video/rem/gen_scenes.py && npm run vendor
  cd video/rem/<scene> && npx hyperframes lint && npx hyperframes render --workers 3 --output ../../../projects/rare-earth-magnets/assets/renders/<scene>.mp4
"""
