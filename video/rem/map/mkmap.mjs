// Land-only maps for the rare earth film (no political borders: PLAYBOOK lessons, fireice).
// Run from a folder with d3-geo@3.1.1, topojson-client@3.1.0, world-atlas@2.0.2 installed:
//   node /home/user/Creator/video/rem/map/mkmap.mjs   -> video/rem/map/map.js
import { geoMercator, geoPath, geoInterpolate } from "d3-geo";
import { feature } from "topojson-client";
import { readFileSync, writeFileSync } from "node:fs";
const W = 1920, H = 1080;
const land50 = (() => { const t = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8")); return feature(t, t.objects.land); })();
const P = {
  pune: [73.86, 18.52], chavara: [76.55, 9.0], aluva: [76.35, 10.1], manavalakurichi: [77.30, 8.15],
  oscom: [85.0, 19.36], srikakulam: [84.1, 18.3], vizag: [83.22, 17.69], tokyo: [139.7, 35.68], baotou: [109.84, 40.65],
  shanghai: [121.47, 31.23], chennai: [80.27, 13.08], mumbai: [72.88, 19.08],
  odisha_c: [85.4, 19.9], ap_c: [82.0, 16.9], tn_c: [78.6, 10.2], kerala_c: [76.45, 9.6], china_c: [104.0, 33.0], japan_c: [138.5, 36.5],
};
function view(name, box) {
  const proj = geoMercator().fitExtent([[80, 60], [W - 80, H - 60]], { type: "MultiPoint", coordinates: box }); proj.clipExtent([[-500, -500], [W + 500, H + 500]]);
  const path = geoPath(proj).digits(1);
  const pts = Object.fromEntries(Object.entries(P).map(([k, v]) => [k, proj(v).map((x) => +x.toFixed(1))]));
  const arc = (a, b, lift = 0.18) => {   // great-circle arc, then bowed up a little so sea routes read as journeys
    const ip = geoInterpolate(P[a], P[b]), n = 90, A = proj(P[a]), B = proj(P[b]);
    const L = Math.hypot(B[0] - A[0], B[1] - A[1]);
    return "M" + Array.from({ length: n + 1 }, (_, i) => { const [x, y] = proj(ip(i / n)); const k = Math.sin(Math.PI * i / n) * lift * L;
      return `${x.toFixed(1)} ${(y - k).toFixed(1)}`; }).join(" L");
  };
  return { name, land: path(land50), pts, arcs: { india_japan: arc("chennai", "tokyo"), china_india: arc("shanghai", "mumbai", 0.12), baotou_shanghai: arc("baotou", "shanghai", 0.05) } };
}
const out = {
  W, H,
  asia: view("asia", [[66, 4], [146, 4], [66, 46], [146, 46]]),
  india: view("india", [[68, 6.5], [90, 6.5], [68, 24.5], [90, 24.5]]),
};
writeFileSync(new URL("./map.js", import.meta.url).pathname,
  "// Generated by mkmap.mjs from world-atlas 2.0.2 (Natural Earth 1:50m land, public domain): land only, no borders.\nwindow.MAP = " + JSON.stringify(out) + ";\n");
