# shared JS: fade/pop helpers and deterministic particles along a path
LIB = """
      const pop = (sel, t, d = 0.45) => tl.fromTo(sel, { autoAlpha: 0, scale: 0.6, transformOrigin: "50% 50%" }, { autoAlpha: 1, scale: 1, duration: d, ease: "back.out(2)", immediateRender: false }, t);
      const fade = (sel, t, d = 0.5) => tl.fromTo(sel, { autoAlpha: 0 }, { autoAlpha: 1, duration: d, ease: "power2.out", immediateRender: false }, t);
      const out = (sel, t, d = 0.4) => tl.to(sel, { autoAlpha: 0, duration: d, ease: "power1.in" }, t);
      const draw = (sel, t, d) => { const p = document.querySelector(sel), L = p.getTotalLength();
        tl.set(p, { strokeDasharray: L, strokeDashoffset: L }, 0); tl.to(p, { strokeDashoffset: 0, duration: d, ease: "power2.inOut" }, t); };
      // n dots ride a path from t0 for the rest of the film; each dot's place is a pure function of time
      function stream(pathSel, groupSel, n, t0, speed, col, r = 7) {
        const p = document.querySelector(pathSel), L = p.getTotalLength(), g = document.querySelector(groupSel), dots = [];
        for (let i = 0; i < n; i++) { const c = document.createElementNS("http://www.w3.org/2000/svg", "circle");
          c.setAttribute("r", r * (0.6 + 0.4 * ((i * 37) % 10) / 10)); c.setAttribute("fill", col); c.setAttribute("opacity", 0); g.appendChild(c); dots.push(c); }
        const o = { t: 0 };
        tl.fromTo(o, { t: 0 }, { t: D, duration: D, ease: "none", immediateRender: false, onUpdate: () => {
          const s = o.t - t0;
          dots.forEach((c, i) => { const born = i * (L / n) / speed; if (s < born) { c.setAttribute("opacity", 0); return; }
            const d = ((s - born) * speed) % L, pt = p.getPointAtLength(d), j = ((i * 53) % 13 - 6);
            c.setAttribute("cx", pt.x + j * 0.8); c.setAttribute("cy", pt.y + ((i * 29) % 11 - 5)); c.setAttribute("opacity", Math.min(1, d / 80, (L - d) / 80)); });
        } }, 0);
      }
"""


def land(v, fill="#123b42", stroke="#3b6a72"):
    return f'<path d="{MAP[v]["land"]}" fill="{fill}" stroke="{stroke}" stroke-width="1.6"/>'


def write(sid, D, svg, js, extra_html=""):
    d = HERE / sid
    d.mkdir(exist_ok=True)
    (d / "index.html").write_text(HEAD.format(id=sid, D=D) + f'      <svg width="1920" height="1080">{svg}</svg>\n' + extra_html +
                                  TAIL.format(id=sid, D=D, js=LIB + js))
    print("wrote", sid)


def pin(x, y, label, cls="lab", dx=26, dy=-18, col="#f2f7f7", pid="", anchor="start"):
    return (f'<g id="{pid}"><circle cx="{x}" cy="{y}" r="11" fill="{col}" stroke="#041215" stroke-width="4"/>'
            f'<text class="{cls}" x="{x + dx}" y="{y + dy}" text-anchor="{anchor}">{label}</text></g>')


