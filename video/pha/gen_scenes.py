# 3. map_india: pins appear on cue (Pimpri 1954; Kakinada; the three parks). 18 s; make_film picks the window.
def map_india():
    a = MAP["india"]; P = a["pts"]
    pins = [("pimpri", "PIMPRI · 1954", "#7fd3e6", 0.4, -260, -20, "start"), ("kakinada", "KAKINADA", "#ff9933", 4.0, 28, 50, "start"),
            ("nakkapalli", "NAKKAPALLI", "#ff9933", 9.0, 28, -22, "start"), ("jambusar", "GUJARAT", "#c9d6d9", 7.5, -34, -20, "end"),
            ("una", "HIMACHAL", "#c9d6d9", 8.2, 28, -18, "start")]
    svg = GRID + land("india")
    js = ""
    for k, lab, col, t, dx, dy, anc in pins:
        x, y = P[k]
        svg += f'<circle id="g_{k}" cx="{x}" cy="{y}" r="90" fill="url(#glowS)" opacity="0"/>' if col == "#ff9933" else ""
        svg += pin(x, y, lab, pid=f"p_{k}", col=col, dx=dx, dy=dy, anchor=anc)
        js += f'      tl.set("#p_{k}", {{ autoAlpha: 0 }}, 0); pop("#p_{k}", {t});\n'
        if col == "#ff9933":
            js += f'      tl.to("#g_{k}", {{ opacity: 1, duration: 1 }}, {t});\n'
    svg += '<text id="both" class="mono" x="1180" y="980" style="font-size:30px;fill:#ff9933" opacity="0">SAME STATE · ANDHRA PRADESH</text>'
    js += '      fade("#both", 10.0);\n'
