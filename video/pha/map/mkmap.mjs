// Land-only maps for the pharma film (no political borders, as in the rare earth film: PLAYBOOK lessons, fireice).
// Run from a folder with d3-geo@3.1.1, topojson-client@3.1.0, world-atlas@2.0.2 installed:
//   node /home/user/Creator/video/pha/map/mkmap.mjs   -> video/pha/map/map.js
import { geoMercator, geoPath, geoInterpolate } from "d3-geo";
import { feature } from "topojson-client";
import { readFileSync, writeFileSync } from "node:fs";
const W = 1920, H = 1080;
const land50 = (() => { const t = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8")); return feature(t, t.objects.land); })();
const P = {
  kakinada: [82.24, 16.99], nakkapalli: [82.72, 17.42], pimpri: [73.80, 18.63], delhi: [77.21, 28.61], mumbai: [72.88, 19.08],
  jambusar: [72.81, 22.05], una: [76.27, 31.47], wuhan: [114.30, 30.59], shijiazhuang: [114.51, 38.04], hyderabad: [78.49, 17.39],
  india_c: [79.0, 22.0], china_c: [104.0, 33.0],
};
function view(name, box) {
  const proj = geoMercator().fitExtent([[80, 60], [W - 80, H - 60]], { type: "MultiPoint", coordinates: box }); proj.clipExtent([[-500, -500], [W + 500, H + 500]]);
  const path = geoPath(proj).digits(1);
  const pts = Object.fromEntries(Object.entries(P).map(([k, v]) => [k, proj(v).map((x) => +x.toFixed(1))]));
  const arc = (a, b, lift = 0.16) => {   // great-circle arc bowed up a little so the route reads as a journey
    const ip = geoInterpolate(P[a], P[b]), n = 90, A = proj(P[a]), B = proj(P[b]);
    const L = Math.hypot(B[0] - A[0], B[1] - A[1]);
    return "M" + Array.from({ length: n + 1 }, (_, i) => { const [x, y] = proj(ip(i / n)); const k = Math.sin(Math.PI * i / n) * lift * L;
      return `${x.toFixed(1)} ${(y - k).toFixed(1)}`; }).join(" L");
  };
  const deg = Math.abs(proj([P.wuhan[0] + 1, P.wuhan[1]])[0] - proj(P.wuhan)[0]);   // pixels per degree of longitude
  return { name, land: path(land50), pts, deg: +deg.toFixed(2),
    arcs: { wuhan_kakinada: arc("wuhan", "kakinada"), shijiazhuang_mumbai: arc("shijiazhuang", "mumbai", 0.12), kakinada_india: arc("kakinada", "delhi", 0.1) } };
}
const out = {
  W, H,
  asia: view("asia", [[64, 5], [124, 5], [64, 42], [124, 42]]),
  india: view("india", [[68, 6.5], [92, 6.5], [68, 35.5], [92, 35.5]]),
  china: view("china", [[96, 22], [124, 22], [96, 42], [124, 42]]),
};
writeFileSync(new URL("./map.js", import.meta.url).pathname,
  "// Generated by mkmap.mjs from world-atlas 2.0.2 (Natural Earth 1:50m land, public domain): land only, no borders.\nwindow.MAP = " + JSON.stringify(out) + ";\n");
