#!/usr/bin/env python3
"""Assemble session A scenes: <scene>.src.html + kit.css/kit.js -> ../<scene>/index.html (self-contained compositions)."""
from pathlib import Path
here = Path(__file__).resolve().parent
css, js = (here / "kit.css").read_text(), (here / "kit.js").read_text()
for src in sorted(here.glob("*.src.html")):
    name = src.name[: -len(".src.html")]
    scene, _, page = name.partition(".")
    out = here.parent / scene / f"{page or 'index'}.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(src.read_text().replace("<head>", "<head>\n    <!-- generated by _A/build.py from _A/" + src.name + "; edit the source, not this file -->", 1).replace("/*KIT_CSS*/", css).replace("/*KIT_JS*/", js))
    print(out.relative_to(here.parent))
