#!/usr/bin/env python3
"""Write a scene's index.html from a small spec file: the shared HyperFrames shell (fonts, layers, timeline registration)
around the scene's own markup and timeline code, so every scene follows the same contract (CLAUDE.md, PLAYBOOK §10).

  python3 video/kavach-railway-reality/_tools/shell.py <scene_dir>        # reads <scene_dir>/scene.py

scene.py defines: TITLE, BODY (HTML inside #root), CSS (extra CSS), LIBS (extra local scripts), JS (timeline code using
`tl`, `D` = duration), and optional HUD text, BG ("slate" or "none"), MODULE (an ES-module script for Three.js scenes).
The duration comes from cues.js (generated from the real VO timing), so data-duration always matches the scene spec.
"""
import json, re, sys
from pathlib import Path

d = Path(sys.argv[1]).resolve()
spec = {}
exec((d / "scene.py").read_text(), spec)
cues = json.loads(re.search(r"window\.CUES = (\{.*\});", (d / "cues.js").read_text(), re.S).group(1))
sid, dur = d.name, cues["duration"]
hud = spec.get("HUD", "")
bg = "url(slate.jpg) center/cover" if spec.get("BG", "slate") == "slate" else "none"
libs = "\n".join(f'<script src="{x}"></script>' for x in spec.get("LIBS", []))
importmap = """<script type="importmap">
  { "imports": { "three": "./vendor/three/three.module.js", "three/addons/": "./vendor/three/jsm/",
    "three/examples/jsm/": "./vendor/three/jsm/", "postprocessing": "./vendor/pp/postprocessing.js",
    "n8ao": "./vendor/pp/N8AO.js", "simplex-noise": "./vendor/noise/simplex-noise.js" } }
</script>""" if spec.get("MODULE") else ""
html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=1920, height=1080" />
<title>{spec['TITLE']}</title>
<!-- generated by video/kavach-railway-reality/_tools/shell.py from scene.py: edit scene.py, then re-run -->
<style>
  @font-face {{ font-family: "Inter"; font-weight: 400; src: url("vendor/fonts/inter-latin-400-normal.woff2") format("woff2"); }}
  @font-face {{ font-family: "Inter"; font-weight: 600; src: url("vendor/fonts/inter-latin-600-normal.woff2") format("woff2"); }}
  @font-face {{ font-family: "Inter"; font-weight: 800; src: url("vendor/fonts/inter-latin-800-normal.woff2") format("woff2"); }}
  @font-face {{ font-family: "Inter"; font-weight: 400 800; src: url("vendor/fonts/inter-latin-ext-600-normal.woff2") format("woff2");
    unicode-range: U+20B9, U+0100-024F, U+2000-206F, U+2190-21FF, U+2248, U+2260, U+2264, U+2265, U+00D7, U+00F7; }}
</style>
<link rel="stylesheet" href="kav.css" />
<style>
  html, body {{ margin: 0; background: #0F172A; }}
  #root {{ position: relative; width: 1920px; height: 1080px; overflow: hidden; background: #0F172A {bg}; font-family: Inter, Arial, sans-serif; color: #F8FAFC; }}
  #schem {{ position: absolute; inset: 0; width: 1920px; height: 1080px; }}
  .tlabel {{ font: 800 22px Inter, Arial, sans-serif; letter-spacing: 0.14em; fill: #94A3B8; }}
  .tlabel.amber {{ fill: #F59E0B; }} .tlabel.red {{ fill: #F87171; }}
  .tnum {{ font: 800 30px Inter, Arial, sans-serif; fill: #F8FAFC; letter-spacing: 0.02em; }}
  #sweep {{ position: absolute; top: -200px; left: -900px; width: 700px; height: 1480px; transform: rotate(14deg);
    background: linear-gradient(90deg, rgba(56,189,248,0), rgba(56,189,248,0.07), rgba(56,189,248,0)); }}
  #vig {{ position: absolute; inset: 0; background: radial-gradient(ellipse at 50% 55%, rgba(0,0,0,0) 55%, rgba(0,0,0,0.55) 100%); }}
  #hud {{ position: absolute; left: 96px; top: 72px; font: 800 22px Inter, Arial, sans-serif; letter-spacing: 0.16em; color: rgba(248,250,252,0.72); }}
  #hud .dot {{ display: inline-block; width: 12px; height: 12px; border-radius: 6px; background: #DC2626; margin-right: 14px; vertical-align: 1px; }}
  .kav-label {{ opacity: 0; }}
{spec.get('CSS', '')}
</style>
{importmap}
</head>
<body>
<div id="root" data-composition-id="{sid}" data-start="0" data-width="1920" data-height="1080" data-duration="{dur}">
{spec['BODY']}
  <div id="sweep" data-layout-allow-occlusion></div>
  <div id="vig" data-layout-allow-occlusion></div>
  {f'<div id="hud"><span class="dot"></span>{hud}</div>' if hud else ''}
{spec.get('OVER', '')}
</div>
<script src="vendor/gsap.min.js"></script>
<script src="cues.js"></script>
<script src="kav.js"></script>
<script src="indsig.js"></script>
{libs}
<script>
  const D = CUES.duration;
  const tl = gsap.timeline({{ paused: true }});
  tl.fromTo("#sweep", {{ x: 0 }}, {{ x: 3200, duration: D, ease: "none" }}, 0);
  {"tl.from('#hud', { opacity: 0, duration: 0.8 }, 0.3); tl.to('#hud .dot', { opacity: 0.25, duration: 0.5, yoyo: true, repeat: Math.max(1, Math.floor(D) - 1), ease: 'sine.inOut' }, 0.4);" if hud else ""}
{spec['JS']}
  window.__timelines = window.__timelines || {{}};
  window.__timelines["{sid}"] = tl;
</script>
{f'<script type="module">{spec["MODULE"]}</script>' if spec.get("MODULE") else ''}
</body>
</html>
"""
(d / "index.html").write_text(html)
print("wrote", d / "index.html", dur)
