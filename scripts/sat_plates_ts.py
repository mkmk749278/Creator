#!/usr/bin/env python3
"""Write a film's satellite plate table (src/plates.ts) from the plate jsons, so code never hard-codes bounds.

Usage: python3 scripts/sat_plates_ts.py films/<slug>   (reads assets/media/sat/*.json, writes remotion/src/plates.ts)
"""
import json
import sys
from pathlib import Path

film = Path(sys.argv[1])
rows = []
credits = set()
for j in sorted((film / 'assets/media/sat').glob('*.json')):
    m = json.loads(j.read_text())
    if not m.get('mapBounds'):
        continue
    name = j.stem
    stem = 'relief' if (j.parent / f'{name}_relief.jpg').exists() else ''
    file = f"assets/media/sat/{name}{'_' + stem if stem else ''}.jpg"
    b = ', '.join(f'{v:.3f}' for v in m['mapBounds'])
    rows.append(f"\t{name}: {{file: '{file}', bounds: [{b}], px: {m['px'][0]}}},")
    credits.add(m.get('credit', ''))
out = film / 'remotion/src/plates.ts'
out.write_text(
    '// Generated by scripts/sat_plates_ts.py from assets/media/sat/*.json: do not edit by hand.\n'
    "import {SatPlate} from '../../../../lib/remotion/map';\n\n"
    'export const PLATES = {\n' + '\n'.join(rows) + '\n} satisfies Record<string, SatPlate>;\n\n'
    '// Credits for the description (PLAYBOOK §11.3)\n'
    + '\n'.join(f'// {c}' for c in sorted(credits) if c) + '\n'
)
print(out, len(rows), 'plates')
