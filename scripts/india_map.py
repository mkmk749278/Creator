#!/usr/bin/env python3
"""Build the film's India map geometry from Natural Earth's India point-of-view countries file (PLAYBOOK §6.6).

Input:  ne_10m_admin_0_countries_ind.geojson (public domain, naturalearthdata.com; the India POV file draws India's
        official boundary: all of Jammu & Kashmir and Ladakh, Arunachal Pradesh, Andaman & Nicobar, Lakshadweep).
Output: lib/remotion/map/indiaGeo.ts: SVG path data per country in a Lambert azimuthal equal-area projection centred
        on India, simplified (Douglas-Peucker), plus the projection constants so pins can be projected at render time.

Usage:  python3 -I scripts/india_map.py path/to/ne_10m_admin_0_countries_ind.geojson lib/remotion/map/indiaGeo.ts
"""
import json
import math
import sys

LON0, LAT0 = 80.0, 22.0
R_KM = 6371.0
KM_PER_UNIT = 3.0  # 1 map unit = 3 km
TOL = 0.45  # simplification tolerance in map units (1.35 km): sharp at 4K
BBOX = (56.0, 2.0, 104.0, 40.0)  # lon/lat window kept for the neighbours
KEEP = ['IND', 'PAK', 'CHN', 'NPL', 'BTN', 'BGD', 'MMR', 'LKA', 'AFG', 'IRN', 'TJK', 'MDV', 'THA', 'LAO', 'KGZ', 'UZB', 'TKM', 'OMN']


def project(lon, lat):
    """Lambert azimuthal equal-area, centred on (LON0, LAT0); returns map units, y down."""
    l, p = math.radians(lon - LON0), math.radians(lat)
    p0 = math.radians(LAT0)
    k = math.sqrt(2.0 / (1.0 + math.sin(p0) * math.sin(p) + math.cos(p0) * math.cos(p) * math.cos(l)))
    x = R_KM * k * math.cos(p) * math.sin(l)
    y = R_KM * k * (math.cos(p0) * math.sin(p) - math.sin(p0) * math.cos(p) * math.cos(l))
    return x / KM_PER_UNIT, -y / KM_PER_UNIT


def dp(pts, tol):
    """Douglas-Peucker on an open polyline (iterative)."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]
        bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        n = math.hypot(dx, dy) or 1e-9
        best, bi = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / n
            if d > best:
                best, bi = d, i
        if best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def dp_ring(pts, tol):
    """Douglas-Peucker on a closed ring: split at the point farthest from the start, simplify both halves."""
    if len(pts) < 8:
        return pts
    x0, y0 = pts[0]
    far = max(range(len(pts)), key=lambda i: (pts[i][0] - x0) ** 2 + (pts[i][1] - y0) ** 2)
    return dp(pts[: far + 1], tol)[:-1] + dp(pts[far:], tol)


def ring_path(ring):
    pts = [project(lon, lat) for lon, lat in ring]
    simp = dp_ring(pts, TOL)
    if len(simp) < 4:
        simp = pts
    return 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in simp[:-1]) + 'Z', len(simp)


def in_bbox(ring):
    return any(BBOX[0] <= lon <= BBOX[2] and BBOX[1] <= lat <= BBOX[3] for lon, lat in ring)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = json.load(open(src, encoding='utf-8'))
    out = {}
    npts = 0
    for f in data['features']:
        pr = f['properties']
        code = pr.get('ADM0_A3_IN') or pr.get('ADM0_A3')
        if code not in KEEP:
            continue
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        paths = []
        for poly in polys:
            outer = poly[0]
            if not in_bbox(outer):
                continue
            d, n = ring_path(outer)
            npts += n
            paths.append(d)
        if paths:
            out[code] = out.get(code, []) + paths
    xs, ys = [], []
    for d in out['IND']:
        for seg in d[1:-1].split('L'):
            x, y = map(float, seg.split())
            xs.append(x)
            ys.append(y)
    bbox = [min(xs), min(ys), max(xs), max(ys)]
    with open(dst, 'w', encoding='utf-8') as fh:
        fh.write('// Generated by scripts/india_map.py from Natural Earth ne_10m_admin_0_countries_ind (public domain).\n')
        fh.write("// India's official boundary (PLAYBOOK §6.6). Do not edit by hand: re-run the script.\n")
        fh.write(f'// Lambert azimuthal equal-area centred on {LON0}E {LAT0}N; 1 unit = {KM_PER_UNIT} km; y down. {npts} points.\n\n')
        fh.write(f'export const MAP_PROJ = {{lon0: {LON0}, lat0: {LAT0}, rKm: {R_KM}, kmPerUnit: {KM_PER_UNIT}}} as const;\n\n')
        fh.write(f'/** India\'s bounding box in map units: [minX, minY, maxX, maxY]. */\nexport const INDIA_BBOX = {json.dumps([round(v, 1) for v in bbox])} as const;\n\n')
        fh.write('/** SVG path data per country (ISO A3, India POV). India first. */\nexport const COUNTRIES: Record<string, string[]> = {\n')
        for code in ['IND'] + [c for c in KEEP if c != 'IND' and c in out]:
            fh.write(f'\t{code}: {json.dumps(out[code])},\n')
        fh.write('};\n')
    print(f'wrote {dst}: {len(out)} countries, {npts} points, India bbox {bbox}')


if __name__ == '__main__':
    main()
