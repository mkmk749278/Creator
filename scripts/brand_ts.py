#!/usr/bin/env python3
"""Write a Remotion project's src/brand.ts from config/brand.yaml (PLAYBOOK §10.2: tokens are never typed by hand).

Usage: scripts/brand_ts.py OUT.ts   (reads the flat `colors:` and `fonts:` maps; no YAML library needed)
"""
import re
import sys
from pathlib import Path

src = Path(__file__).resolve().parent.parent / "config" / "brand.yaml"
sections: dict[str, dict[str, str]] = {}
cur = None
for line in src.read_text().splitlines():
    if re.match(r"^\w+:\s*(#.*)?$", line):
        cur = line.split(":")[0]
        sections[cur] = {}
    elif cur and (m := re.match(r'^\s+(\w+):\s*"([^"]+)"', line)):
        sections[cur][m.group(1)] = m.group(2)
out = ["// Generated by scripts/brand_ts.py from config/brand.yaml. Do not edit by hand.\n"]
for name in ("colors", "fonts"):
    body = ",\n".join(f"  {k}: '{v}'" for k, v in sections.get(name, {}).items())
    out.append(f"export const {name} = {{\n{body},\n}} as const;\n")
Path(sys.argv[1]).write_text("\n".join(out))
print(f"wrote {sys.argv[1]}")
