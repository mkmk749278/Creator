// Build the whiteboard engine's single-line (pen-path) fonts: video/lib/whiteboard/wb-fonts.js
// Source: EMS / Hershey SVG fonts shipped in the pinned `hersheytext` package (EMS fonts: SIL Open Font License;
// Hershey data: public domain). Each glyph is a list of pen strokes, so text can be *written* stroke by stroke.
// Adds glyphs the fonts lack (₹ and a few marks) in the same pen style.  Usage: node scripts/build_wb_fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "node_modules/hersheytext/svg_fonts");
const FONTS = { felix: "EMSFelix", readability: "EMSReadability", nixish: "EMSNixish", allure: "EMSAllure",
  script: "HersheyScript1", sans: "HersheySans1", tech: "EMSTech" };

const ent = (s) => s.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d)).replace(/&quot;/g, '"').replace(/&amp;/g, "&")
  .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&apos;/g, "'");
const attr = (tag, name) => { const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`)); return m ? m[1] : null; };

// "M x y L x y ..." -> [[x,y,x,y,...], ...] (one array per pen-down stroke). The fonts use only M and L.
function strokes(d) {
  const out = []; let cur = null, op = "M", x = 0, y = 0;
  const tok = d.match(/[MLml]|-?\d*\.?\d+(?:e[-+]?\d+)?/g);
  for (let i = 0; i < tok.length; ) {
    if (/[MLml]/.test(tok[i])) { op = tok[i++]; continue; }
    const a = +tok[i], b = +tok[i + 1]; i += 2;
    const rel = op === "m" || op === "l";
    x = rel ? x + a : a; y = rel ? y + b : b;
    if (op === "M" || op === "m") { cur = [x, y]; out.push(cur); op = op === "M" ? "L" : "l"; }
    else cur.push(x, y);
  }
  return out.map((s) => s.map((v) => Math.round(v * 10) / 10));
}

// Extra pen glyphs, drawn in a cap-height box (y up, baseline 0). c = cap height, w = advance.
function extras(c) {
  const w = Math.round(c * 0.86), x0 = Math.round(c * 0.08), x1 = Math.round(c * 0.66);
  const bowl = []; // ₹: bowl from the top-left round to the middle-left, then the leg down to the baseline
  for (let k = 0; k <= 12; k++) { const a = -Math.PI / 2 + (Math.PI * k) / 12; bowl.push(Math.round(x0 + c * 0.05 + c * 0.32 * Math.cos(a) + (k ? 0 : 0)), Math.round(c * 0.82 - c * 0.2 - c * 0.2 * Math.sin(a))); }
  return {
    "₹": { w, s: [[x0, c, x1 + c * 0.1, c], [x0, c * 0.72, x1 + c * 0.1, c * 0.72],
      [x0, c, ...bowl.slice(2), x0, c * 0.42, x1, 0]].map((s) => s.map(Math.round)) },
    "×": { w: Math.round(c * 0.7), s: [[c * 0.1, c * 0.6, c * 0.55, c * 0.15], [c * 0.55, c * 0.6, c * 0.1, c * 0.15]].map((s) => s.map(Math.round)) },
    "→": { w: Math.round(c * 1.1), s: [[c * 0.05, c * 0.4, c * 0.95, c * 0.4], [c * 0.7, c * 0.62, c * 0.97, c * 0.4, c * 0.7, c * 0.18]].map((s) => s.map(Math.round)) },
    "✓": { w: Math.round(c * 0.8), s: [[c * 0.05, c * 0.35, c * 0.3, c * 0.05, c * 0.75, c * 0.75]].map((s) => s.map(Math.round)) },
    "≠": { w: Math.round(c * 0.8), s: [[c * 0.08, c * 0.52, c * 0.68, c * 0.52], [c * 0.08, c * 0.25, c * 0.68, c * 0.25], [c * 0.55, c * 0.72, c * 0.2, c * 0.05]].map((s) => s.map(Math.round)) },
    "≈": { w: Math.round(c * 0.86), s: [0.52, 0.24].map((y0) => Array.from({ length: 9 }, (_, k) => [c * (0.08 + 0.075 * k), c * (y0 + 0.07 * Math.sin((k / 8) * Math.PI * 2))]).flat()).map((s) => s.map(Math.round)) },
    "…": { w: Math.round(c * 0.9), s: [0.15, 0.4, 0.65].map((f) => [c * f, c * 0.03, c * f + 4, c * 0.03]).map((s) => s.map(Math.round)) },
  };
}

const out = {};
for (const [key, file] of Object.entries(FONTS)) {
  const svg = readFileSync(join(SRC, file + ".svg"), "utf8");
  const font = svg.match(/<font\b[^>]*>/)[0], face = svg.match(/<font-face\b[^>]*>/)[0];
  const def = +attr(font, "horiz-adv-x");
  const cap = +(attr(face, "cap-height") || attr(face, "ascent") * 0.7);
  const g = {};
  for (const tag of svg.match(/<glyph\b[^>]*>/g)) {
    const u = attr(tag, "unicode"); if (u === null) continue;
    const ch = ent(u); if ([...ch].length !== 1) continue;
    const d = attr(tag, "d");
    if (d && /[CcSsQqAa]/.test(d)) continue; // a few accented glyphs use curves; the pen engine skips them
    g[ch] = { w: +(attr(tag, "horiz-adv-x") || def), s: d ? strokes(d) : [] };
  }
  for (const [ch, v] of Object.entries(extras(cap))) if (!g[ch] || !g[ch].s.length) g[ch] = v;
  out[key] = { name: file, cap, em: +attr(face, "units-per-em"), def, glyphs: g,
    license: /EMS/.test(file) ? "SIL Open Font License 1.1 (EMS fonts, Evil Mad Scientist / Sheldon B. Michaels)" : "Hershey font data (public domain)" };
}
const js = "// Generated by scripts/build_wb_fonts.mjs from hersheytext@2.0.0 — do not edit.\n" +
  "window.WB_FONTS = " + JSON.stringify(out) + ";\n";
writeFileSync(join(root, "video/lib/whiteboard/wb-fonts.js"), js);
console.log("wrote", Object.keys(out).join(", "), (js.length / 1024).toFixed(0) + " KB");
